/** 'Texas' -> 'TX'. A two-letter code passes through upper-cased; anything else is returned as given. */
export function usStateCode(v: unknown): string {
  const s = str(v);
  if (!s) return '';
  if (/^[A-Za-z]{2}$/.test(s)) return s.toUpperCase();
  return US_STATES[s.toLowerCase()] ?? s;
}
