/* eslint-disable no-console */
// Regenerates packages/shared/src/data/cbsa.ts, the county -> metro
// (CBSA) crosswalk, from the Census Bureau's delineation file (List 1,
// public domain). Rerun when OMB issues a new delineation:
//
//   npx tsx scripts/generate-cbsa.ts [list1 xlsx url]
//
// Kept: each CBSA's code, title and type, and each county's CBSA and name.
// Metropolitan divisions and combined areas are not used by market
// intelligence.
import { writeFileSync } from 'fs';
import { resolve } from 'path';
import PizZip from 'pizzip';

const SOURCE =
  process.argv[2] ??
  'https://www2.census.gov/programs-surveys/metro-micro/geographies/reference-files/2023/delineation-files/list1_2023.xlsx';
const VINTAGE = '2023-07';
const OUT = resolve(__dirname, '../packages/shared/src/data/cbsa.ts');

function decode(s: string): string {
  return s
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&');
}

/** The cells of the first sheet, by row, keyed by column letter. */
function readSheet(zip: PizZip): Array<Record<string, string>> {
  const shared = (zip.file('xl/sharedStrings.xml')?.asText() ?? '')
    .split('<si>')
    .slice(1)
    .map((si) =>
      decode(
        [...si.matchAll(/<t[^>]*>([^<]*)<\/t>/g)].map((m) => m[1]).join(''),
      ),
    );
  const sheet = zip.file('xl/worksheets/sheet1.xml')?.asText();
  if (!sheet) throw new Error('sheet1.xml missing');
  const rows: Array<Record<string, string>> = [];
  for (const row of sheet.matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)) {
    const cells: Record<string, string> = {};
    for (const c of row[1].matchAll(
      /<c r="([A-Z]+)\d+"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g,
    )) {
      const [, col, attrs, body = ''] = c;
      const v = /<v>([^<]*)<\/v>/.exec(body)?.[1];
      const inline = /<t[^>]*>([^<]*)<\/t>/.exec(body)?.[1];
      cells[col] =
        v == null
          ? decode(inline ?? '')
          : /t="s"/.test(attrs)
            ? shared[Number(v)]
            : decode(v);
    }
    rows.push(cells);
  }
  return rows;
}

async function main() {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`${SOURCE}: ${res.status}`);
  const rows = readSheet(new PizZip(Buffer.from(await res.arrayBuffer())));

  const header = rows.findIndex((r) => r.A === 'CBSA Code');
  if (header < 0) throw new Error('header row not found');
  const h = rows[header];
  const col = (name: string) => {
    const k = Object.keys(h).find((key) => h[key] === name);
    if (!k) throw new Error(`column "${name}" not found`);
    return k;
  };
  const C = {
    code: col('CBSA Code'),
    title: col('CBSA Title'),
    type: col('Metropolitan/Micropolitan Statistical Area'),
    state: col('FIPS State Code'),
    county: col('FIPS County Code'),
    countyName: col('County/County Equivalent'),
  };

  const cbsas = new Map<string, { title: string; metro: boolean }>();
  const counties = new Map<string, string>();
  const names = new Map<string, string>();
  for (const r of rows.slice(header + 1)) {
    const code = r[C.code];
    if (!/^\d{5}$/.test(code ?? '')) continue;
    const fips = `${r[C.state].padStart(2, '0')}${r[C.county].padStart(3, '0')}`;
    if (!/^\d{5}$/.test(fips))
      throw new Error(`bad county FIPS in CBSA ${code}`);
    cbsas.set(code, {
      title: r[C.title],
      metro: /^Metropolitan/.test(r[C.type]),
    });
    counties.set(fips, code);
    names.set(fips, r[C.countyName]);
  }
  if (cbsas.size < 900 || counties.size < 1800) {
    throw new Error(
      `suspiciously small: ${cbsas.size} CBSAs, ${counties.size} counties`,
    );
  }

  const cbsaLines = [...cbsas.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([code, c]) =>
        `  '${code}': [${JSON.stringify(c.title)}, ${c.metro ? 1 : 0}],`,
    );
  const countyLines: string[] = [];
  const sorted = [...counties.entries()].sort(([a], [b]) => a.localeCompare(b));
  for (let i = 0; i < sorted.length; i += 6) {
    countyLines.push(
      '  ' +
        sorted
          .slice(i, i + 6)
          .map(([fips, code]) => `'${fips}': '${code}',`)
          .join(' '),
    );
  }

  const nameLines = [...names.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([fips, name]) => `  '${fips}': ${JSON.stringify(name)},`);

  const out = `// Generated by scripts/generate-cbsa.ts. Do not edit by hand.
// Source: U.S. Census Bureau, delineation file List 1 (July 2023, OMB
// Bulletin 23-01), ${SOURCE}
// Public domain. ${cbsas.size} CBSAs, ${counties.size} counties.

/** The OMB delineation the crosswalk follows. */
export const CBSA_VINTAGE = '${VINTAGE}';

/** CBSA code -> [title, 1 for metropolitan or 0 for micropolitan]. */
export const CBSA_TITLES: Record<string, [string, 0 | 1]> = {
${cbsaLines.join('\n')}
};

/** Five-digit county FIPS -> CBSA code. Counties outside any CBSA are absent. */
export const COUNTY_CBSA: Record<string, string> = {
${countyLines.join('\n')}
};

/** Five-digit county FIPS -> county name, for the same counties. */
export const COUNTY_NAMES: Record<string, string> = {
${nameLines.join('\n')}
};
`;
  writeFileSync(OUT, out, 'utf8');
  console.log(`wrote ${OUT}: ${cbsas.size} CBSAs, ${counties.size} counties`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
