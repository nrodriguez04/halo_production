/* eslint-disable no-console */
// Regenerates apps/api/src/compliance/nanp-time-zones.ts from Google
// libphonenumber's prefix -> time zone data (Apache-2.0), pinned to a commit.
//
//   npx tsx scripts/generate-nanp-time-zones.ts <libphonenumber commit sha>
//
// Prefixes longer than an area code (an area code split between zones by
// exchange) are folded into the area code's set. Quiet hours require a send
// to be allowed in every zone the recipient might be in, so the union is the
// conservative reading.
import { writeFileSync } from 'fs';
import { resolve } from 'path';

const ref = process.argv[2];
if (!ref) {
  console.error('usage: tsx scripts/generate-nanp-time-zones.ts <commit sha>');
  process.exit(1);
}

const SOURCE = `https://raw.githubusercontent.com/google/libphonenumber/${ref}/resources/timezones/map_data.txt`;
const OUT = resolve(__dirname, '../apps/api/src/compliance/nanp-time-zones.ts');

async function main() {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`${SOURCE}: ${res.status}`);
  const text = await res.text();

  const zonesByAreaCode = new Map<string, Set<string>>();
  for (const line of text.split(/\r?\n/)) {
    if (!line || line.startsWith('#')) continue;
    const [prefix, zones] = line.split('|');
    if (!prefix?.startsWith('1') || prefix.length < 4 || !zones) continue;
    const areaCode = prefix.slice(1, 4);
    if (!/^[2-9]\d\d$/.test(areaCode)) continue;
    const set = zonesByAreaCode.get(areaCode) ?? new Set<string>();
    for (const zone of zones.split('&')) set.add(zone.trim());
    zonesByAreaCode.set(areaCode, set);
  }

  const entries = [...zonesByAreaCode.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([code, zones]) =>
        `  '${code}': [${[...zones].sort().map((z) => `'${z}'`).join(', ')}],`,
    );

  const body = `// GENERATED by scripts/generate-nanp-time-zones.ts - do not edit by hand.
//
// NANP area code -> IANA time zones, from Google libphonenumber
// resources/timezones/map_data.txt at commit ${ref}.
// Copyright (C) 2012 The Libphonenumber Authors. Licensed under the Apache
// License, Version 2.0: http://www.apache.org/licenses/LICENSE-2.0
//
// An area code split between zones lists every zone it spans.

export const NANP_AREA_CODE_TIME_ZONES: Readonly<
  Record<string, readonly string[]>
> = {
${entries.join('\n')}
};
`;
  writeFileSync(OUT, body);
  console.log(`wrote ${zonesByAreaCode.size} area codes to ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
